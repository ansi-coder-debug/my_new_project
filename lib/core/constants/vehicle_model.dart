  // Get models based on vehicle type and make
  static List<String> getModelsForMake(String vehicleType, String make) {
    if (make.isEmpty) return [];
    
    final modelsMap = vehicleType.toLowerCase() == 'car' ? carModels : bikeModels;
    final models = modelsMap[make];
    
    if (models == null) return [];
    
    // Extract just the model names
    return models.map<String>((model) => model['name'] as String).toList();
  }

  // Get capacity for a specific model
  static dynamic getCapacityForModel(String vehicleType, String make, String model) {
    if (make.isEmpty || model.isEmpty) return null;
    
    final modelsMap = vehicleType.toLowerCase() == 'car' ? carModels : bikeModels;
    final models = modelsMap[make];
    
    if (models == null) return null;
    
    final modelData = models.firstWhere(
      (m) => m['name'] == model,
      orElse: () => {},
    );
    
    return modelData['capacity'];
  }
